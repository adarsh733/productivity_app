export function runPipeline(): void {
  console.log('=== ARTICULATE CONTENT PIPELINE RUNNER ===');
  const candidates = getAllCandidates();
  console.log(`Loaded ${candidates.length} candidate cards across 6 high-value content decks.`);

  // Process through validation, deduplication, and cold verification
  const { processed, reportMarkdown } = processCandidates(candidates);

  // Write staging file and review report
  const STAGING_DIR = path.resolve(__dirname, '../../src/content/staging');
  if (!fs.existsSync(STAGING_DIR)) {
    fs.mkdirSync(STAGING_DIR, { recursive: true });
  }

  fs.writeFileSync(path.join(STAGING_DIR, 'candidates.json'), JSON.stringify(processed, null, 2), 'utf-8');
  fs.writeFileSync(path.join(STAGING_DIR, 'review-report.md'), reportMarkdown, 'utf-8');
  console.log(`Saved staging candidates and review report to ${STAGING_DIR}/review-report.md`);

  const approved = processed.filter((c) => c.status === 'approved');
  console.log(`\nVerification Results: ${approved.length} / ${processed.length} candidates APPROVED.`);

  if (approved.length === processed.length) {
    console.log('Promoting approved candidates to active seed library...');
    const result = promoteApprovedCandidatesToSeeds(processed);
    console.log(`Successfully promoted ${result.promotedCount} cards into active seed JSON files!`, result.promotedByType);
  } else {
    console.warn(`WARNING: ${processed.length - approved.length} cards failed verification and were NOT promoted.`);
  }
}

runPipeline();

