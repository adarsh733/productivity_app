// Helper to create typed CandidateCard
function createCandidate<T extends Card>(id: string, data: Omit<T, 'id' | 'batchId' | 'source' | 'status' | 'createdAt'>): CandidateCard<T> {
  return {
    candidateId: `cand-${id}`,
    batchId: BATCH_ID,
    status: 'candidate',
    createdAt: NOW,
    data: {
      id,
      ...data,
      source: 'seed',
      status: 'active',
      createdAt: NOW,
    } as T,
  };
}

